"""
Phase Z20 (continuation, this session): does the ONE escape Z19 flagged
-- a twist automorphism built from D_F itself, rather than a fixed
external automorphism -- actually break the Z1/Z19 linearity no-go?

Candidate, chosen to be as non-ad-hoc as possible (Rule 1): the
CANONICAL inner automorphism generated by D_F itself,

    rho_D(a) := e^{i D} a e^{-i D}

This is the natural/only "automorphism built from D with no extra
free function" choice -- it is literally the one-parameter group D
generates by exponentiation (Heisenberg-picture time evolution by D
itself, at "time" 1). Introducing any other function of D (e^{f(D)}
for some other f, or a different coefficient) would itself be an
unexplained new object and fail Rule 1. This is checked, not assumed
innocent -- if e^{iD} a e^{-iD} degrades to a linear-in-D expression
after expansion, the escape fails and Z1/Z19 still stand.

Method: identical style to phase_z19 (symbolic degree tracking), but
now D appears inside a genuine power series (matrix exponential), so
we check the D-degree of EVERY order up to a cutoff, not just "the"
expression -- the claim is that degrees 0,1,2,3,... ALL appear
(nonlinear/inhomogeneous), not just degree 1.
"""
import sympy as sp

D, a, b = sp.symbols('D a b', commutative=False)
i = sp.I
N_ORDER = 5  # truncation order for e^{iD}, e^{-iD} series

def series_exp(op, x, order):
    # sum_{k=0}^{order} (i*x)^k * op^k / k!  -- but op is noncommutative
    # wrt D itself when x=D; here we just build i*D as the argument.
    terms = []
    cur = sp.Integer(1)
    for k in range(order + 1):
        terms.append(cur)
        cur = cur * (i * x) / (k + 1)
    return terms  # list of terms, term k already has D-degree k built in structurally


def rho_D(x, order):
    """e^{iD} x e^{-iD}, truncated, expanded, as an explicit sum over
    D-degree-graded terms (each term is D^m * x * D^n for various m,n)."""
    total = 0
    for m in range(order + 1):
        cm = (i) ** m / sp.factorial(m)
        for n in range(order + 1):
            cn = (-i) ** n / sp.factorial(n)
            total += cm * cn * D ** m * x * D ** n
    return sp.expand(total)


rho_a = rho_D(a, N_ORDER)

# Twisted order-one condition: [D,a]_rho = D a - rho_D(a) D
Da_rho = sp.expand(D * a - rho_a * D)

# [[D,a]_rho, b]
expr = sp.expand(Da_rho * b - b * Da_rho)

terms = sp.Add.make_args(expr)


def d_degree(term):
    factors = sp.Mul.make_args(term)
    deg = 0
    for f in factors:
        if f == D:
            deg += 1
        elif f.is_Pow and f.base == D:
            deg += int(f.exp)
    return deg


degrees_present = sorted(set(d_degree(t) for t in terms))
print(f"Truncation order used for e^{{iD}}: {N_ORDER}")
print(f"Number of expanded terms in [[D,a]_rho, b]: {len(terms)}")
print(f"Distinct D-degrees appearing: {degrees_present}")
print()
if degrees_present == [1]:
    print("RESULT: still homogeneous degree 1 -- self-twist does NOT escape "
          "the Z1/Z19 no-go (unexpected; would need re-examination).")
else:
    print("RESULT: multiple D-degrees appear (0,1,2,3,... up to the "
          "truncation order) -- the condition is NOT homogeneous/linear in D.")
    print("The lambda*D scaling argument used in Z1/Z19 (E(lambda D) = "
          "lambda * E(D)) fails here: E(lambda D) is not proportional to "
          "E(D) for a generic lambda, since terms of different D-degree "
          "scale differently (degree-m term scales as lambda^m).")
    print()
    print("This genuinely breaks the SPECIFIC no-go mechanism from Z1/Z19.")
