"""
Phase Z15 (this session) -- Z14's flagged open door: a NON-minimal
SU(3)_f-breaking sector might evade Theorem B-3's ε=0 result. The
standard non-minimal choice in flavor-model building is a flavon in
the ADJOINT (8) of SU(3)_f rather than the fundamental (3) Theorem B-3
covers. An adjoint's invariant ring is generated by tr(Φ²) and tr(Φ³)
(two independent Casimirs, not one) -- a generic potential in two
invariants generically DOES have its minimum away from Φ=0, at a
diagonal Φ (any traceless Hermitian matrix is gauge-equivalent to a
diagonal one), spontaneously breaking SU(3)_f -> U(1)xU(1) (the
Cartan). This is exactly the textbook "hierarchical VEV" flavon setup.

This phase does NOT re-derive the adjoint potential's minimization in
full (that's a standard, separate exercise) -- it does the two things
that actually matter for THIS project's target:

  1. Test directly what survives the order-one condition when only the
     UNBROKEN low-energy gauge symmetry (the Cartan U(1)xU(1), not the
     full 8-generator su(3)_F) is imposed -- this is the correct
     leading-order picture once SU(3)_f is broken by such a flavon:
     the massive, broken-generator gauge bosons no longer impose an
     exact order-one condition (their effect becomes a suppressed
     higher-dimension operator -- the FN mechanism itself).
  2. Honestly count the new free parameters this scenario introduces
     (per POST_AUDIT_TARGET.md's repeated netting requirement) and net
     them against whatever step 1 saves, rather than presenting step 1
     alone as if it were free.
"""
import os
import sys
import numpy as np
from numpy import kron

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', 'support'))
from z2_hilbert_space import order_one_commutator, build_su3f_generators  # noqa: E402
from phase_z10_real_structure_ansatz import (  # noqa: E402
    load_gammas, build_C_mat, embed_doubled, gamma_prod, E_gen, P,
    sym_constraint_real, realify, BASIS_IDX, run_channel as run_channel_full8,
)

CARTAN_IDX = [2, 7]  # su3f indices of the two diagonal (Cartan) generators


def run_channel_cartan_only(name, Y_H, sym_sign, su3f):
    """Same method as Z9/Z10's run_channel, but the su(3)_F loop is
    restricted to the 2x2=4 Cartan-generator pairs instead of the full
    8x8=64 -- the residual low-energy gauge symmetry after an adjoint
    flavon breaks SU(3)_f -> U(1)xU(1)."""
    Constraint_real = sym_constraint_real(sym_sign)
    GtG = Constraint_real.T @ Constraint_real

    for i in CARTAN_IDX:
        for j in CARTAN_IDX:
            a_HF = kron(np.eye(32, dtype=complex), su3f[i])
            beta_prime = P @ np.eye(32, dtype=complex).conjugate() @ np.linalg.inv(P)
            Jb_HF = kron(beta_prime, su3f[j].conjugate())
            imgs = []
            for (p, q) in BASIS_IDX:
                Ygen_pq = E_gen(p, q)
                Y_full_pq = kron(Y_H, Ygen_pq)
                D_F_pq = embed_doubled(Y_full_pq)
                Lpq = order_one_commutator(D_F_pq, a_HF, Jb_HF)
                imgs.append(Lpq.flatten())
            L = np.array(imgs).T
            Lr = realify(L)
            GtG += Lr.T @ Lr

    rank = np.linalg.matrix_rank(GtG, tol=1e-6)
    w_eig, v_eig = np.linalg.eigh(GtG)
    surviving = 18 - rank
    print(f'--- {name} (Cartan-only, 4 pairs) ---')
    print('surviving real dim:', surviving, f'  (= {surviving/2:.0f} complex)')
    print('smallest eigenvalues:', np.round(w_eig[:6], 4))
    null_basis = v_eig[:, w_eig < 1e-6 * max(w_eig)]
    for kk in range(null_basis.shape[1]):
        vec = null_basis[:, kk]
        re = vec[:9].reshape(3, 3)
        im = vec[9:].reshape(3, 3)
        if np.max(np.abs(re)) > 1e-6 or np.max(np.abs(im)) > 1e-6:
            print(f'  null vec {kk}: Re=\n{np.round(re,3)}\n  Im=\n{np.round(im,3)}')
    return surviving, null_basis


def run():
    G = load_gammas()
    Gamma_F = (1j ** 5) * G[0] @ G[1] @ G[2] @ G[3] @ G[4] @ G[5] @ G[6] @ G[7] @ G[8] @ G[9]
    w, v = np.linalg.eigh(Gamma_F)
    V = v[:, w.real > 0]
    C_mat = build_C_mat(G)
    su3f = build_su3f_generators()

    Y10 = V.conj().T @ (C_mat @ G[0]) @ V
    Y120 = V.conj().T @ (C_mat @ gamma_prod(G, (0, 1, 2))) @ V

    from itertools import combinations
    n, k = 10, 5
    forms5 = list(combinations(range(n), k))
    n5 = len(forms5)

    def eps_sign(tup):
        if len(set(tup)) != n:
            return 0
        parity = 1
        for i in range(n):
            for j in range(i + 1, n):
                if tup[i] > tup[j]:
                    parity *= -1
        return parity

    Hodge = np.zeros((n5, n5))
    for i, fi in enumerate(forms5):
        for j, fj in enumerate(forms5):
            val = eps_sign(tuple(fj) + tuple(fi))
            if val != 0:
                Hodge[i, j] = float(val)
    P_sd = (np.eye(n5) - 1j * Hodge) / 2
    gamma5_list = [gamma_prod(G, t) for t in forms5]
    Usvd, ssvd, Vhsvd = np.linalg.svd(P_sd)
    Y126 = (V.conj().T @ (C_mat @ sum(Usvd[kk, 0] * gamma5_list[kk] for kk in range(n5))) @ V) / np.sqrt(2)

    print('=' * 70)
    print('SANITY CHECK: full 8-generator su(3)_F (should match Z9/Z10 exactly)')
    print('=' * 70)
    r10_full, _ = run_channel_full8('M10', Y10, 1, su3f, False)
    r120_full, _ = run_channel_full8('M120', Y120, -1, su3f, False)
    r126_full, _ = run_channel_full8('M126', Y126, 1, su3f, False)

    print()
    print('=' * 70)
    print('Cartan-only U(1)xU(1) (residual symmetry after adjoint-flavon breaking)')
    print('=' * 70)
    r10_cart, n10 = run_channel_cartan_only('M10', Y10, 1, su3f)
    r120_cart, n120 = run_channel_cartan_only('M120', Y120, -1, su3f)
    r126_cart, n126 = run_channel_cartan_only('M126', Y126, 1, su3f)

    print()
    print('=' * 70)
    print('SUMMARY: full su(3)_F  vs  Cartan-only residual')
    print('=' * 70)
    print(f'{"channel":8s} {"full-8 (real)":15s} {"Cartan-4 (real)":18s} {"Cartan-4 (complex)":18s}')
    print(f'{"M10":8s} {r10_full:<15d} {r10_cart:<18d} {r10_cart/2:<18.0f}')
    print(f'{"M120":8s} {r120_full:<15d} {r120_cart:<18d} {r120_cart/2:<18.0f}')
    print(f'{"M126":8s} {r126_full:<15d} {r126_cart:<18d} {r126_cart/2:<18.0f}')


if __name__ == '__main__':
    run()
