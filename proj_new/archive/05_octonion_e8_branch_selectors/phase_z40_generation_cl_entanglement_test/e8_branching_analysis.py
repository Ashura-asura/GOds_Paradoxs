"""
Task 2 -- search for E8-induced generation asymmetry.

Question: does E8 contain a preferred breaking direction for SU(3)_f
that is ALGEBRAICALLY SELECTED (forced by the root system itself),
as opposed to MANUALLY SELECTED (an externally chosen Cartan direction
or flavon VEV)?

Method: build the full 240-root E8 system (same SO(16) recipe as
phase_a2_e8_core.py, rebuilt here rather than imported, per Task 1's
"reproduce, don't assume" instruction). Search for a rank-2 sub-root-
system (A2 = SU(3)) such that its orthogonal complement among the 240
roots has exactly 72 roots (= E6's root count) -- this is the
computational signature of a genuine E6 x SU(3)_f maximal embedding via
extended-Dynkin-diagram folding (Borel-de Siebenthal), not assumed but
verified against the raw root data.

Once found, ask: is there anything in the FULL E8 structure (240 roots,
Weyl group) that prefers one Cartan direction of that A2 over another,
without an external flavon input? The only "for free" discrete
structure available is the A2's OWN Weyl group (generated by reflections
in its 2 simple roots) -- this is checked directly by orbit-counting,
not asserted to be S3.
"""
import numpy as np
from itertools import product as iproduct, combinations
import json

# --- Build the 240 E8 roots (SO(16) embedding), rebuilt independently ---
roots = []
for i in range(8):
    for j in range(i + 1, 8):
        for s1 in (-1, 1):
            for s2 in (-1, 1):
                v = np.zeros(8)
                v[i] = s1
                v[j] = s2
                roots.append(v)
for bits in iproduct([-1, 1], repeat=8):
    if sum(bits) % 4 == 0:
        roots.append(np.array(bits, dtype=float) * 0.5)
roots = np.unique(np.round(roots, 10), axis=0)
assert len(roots) == 240, f"expected 240 roots, got {len(roots)}"


def dot(a, b):
    return float(np.dot(a, b))


def find_a2_with_e6_complement(roots, max_tries=40000, seed=0):
    """
    Search for two roots r1, r2 with r1.r2 = -1 (the A2 Cartan condition
    at ||r||^2=2 normalization), such that the roots orthogonal to BOTH
    r1 and r2 number exactly 72 (E6's root count). Returns the full A2
    root set (6 roots) and the orthogonal-complement root set (E6, 72
    roots) once found.
    """
    rng = np.random.default_rng(seed)
    idx = np.arange(len(roots))
    tries = 0
    for i, j in combinations(range(len(roots)), 2):
        tries += 1
        if tries > max_tries:
            break
        r1, r2 = roots[i], roots[j]
        if abs(dot(r1, r2) + 1.0) < 1e-9:  # r1.r2 == -1
            # generate the A2 orbit: 6 roots by Weyl reflections
            a2_roots = generate_a2_orbit(r1, r2)
            if len(a2_roots) != 6:
                continue
            # orthogonal complement among all 240 roots
            orth = [r for r in roots if all(abs(dot(r, a)) < 1e-9 for a in a2_roots)]
            if len(orth) == 72:
                return a2_roots, orth, tries
    return None, None, tries


def reflect(v, alpha):
    """Reflect v through the hyperplane orthogonal to root alpha (||alpha||^2=2)."""
    return v - dot(v, alpha) * alpha


def generate_a2_orbit(r1, r2):
    """
    For two roots with (r1,r2) = -1 at ||r||^2 = 2 (i.e. 120 degrees apart,
    the A2 simple-root condition), the A2 root system is exactly
    {r1, r2, -r1, -r2, r1+r2, -(r1+r2)} -- 6 roots. This is the standard
    closed-form A2 root system, not something that needs to be discovered
    by search; confirmed here by explicit construction rather than by the
    general (and, as first attempted, buggy) BFS reflection closure.
    """
    third = r1 + r2
    assert np.isclose(np.dot(third, third), 2.0), "r1+r2 should also be a root for A2"
    return [r1, r2, -r1, -r2, third, -third]


def weyl_group_order(simple_roots, seed_vector, max_iter=2000):
    """
    Orbit-count the Weyl group generated by reflections in `simple_roots`,
    acting on a generic seed vector. The orbit size equals the Weyl group
    order for a generic (non-fixed) seed.
    """
    orbit = {tuple(np.round(seed_vector, 8))}
    frontier = [seed_vector]
    it = 0
    while frontier and it < max_iter:
        it += 1
        new_frontier = []
        for v in frontier:
            for alpha in simple_roots:
                rv = np.round(reflect(v, alpha), 8)
                key = tuple(rv)
                if key not in orbit:
                    orbit.add(key)
                    new_frontier.append(rv)
        frontier = new_frontier
    return len(orbit)


